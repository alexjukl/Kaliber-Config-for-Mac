    /// Modifier mask bit for a modifier usage (0xE0–0xE7), or nil.
    public static func modifierBit(for usage: UInt8) -> UInt8? {
        switch usage {
        case 0xE0, 0xE4: return 0x01
        case 0xE1, 0xE5: return 0x02
        case 0xE2, 0xE6: return 0x04
        case 0xE3, 0xE7: return 0x08
        default: return nil
        }
    }
}
