import Foundation

/// HID keyboard/keypad usage helpers (USB HID Usage Tables §10) plus macOS virtual-key mapping.
public enum HIDUsage {
    public static let names: [UInt8: String] = {
        var m: [UInt8: String] = [:]
        for (i, c) in "abcdefghijklmnopqrstuvwxyz".enumerated() { m[UInt8(0x04 + i)] = String(c).uppercased() }
        for i in 0..<9 { m[UInt8(0x1E + i)] = "\(i + 1)" }
        m[0x27] = "0"
        let named: [UInt8: String] = [
            0x28: "Return", 0x29: "Escape", 0x2A: "Backspace", 0x2B: "Tab", 0x2C: "Space", 0x2D: "-", 0x2E: "=", 0x2F: "[", 0x30: "]",
            0x31: "\\", 0x33: ";", 0x34: "'", 0x35: "`", 0x36: ",", 0x37: ".", 0x38: "/", 0x39: "Caps Lock",
            0x46: "Print Screen", 0x47: "Scroll Lock", 0x48: "Pause", 0x49: "Insert", 0x4A: "Home", 0x4B: "Page Up", 0x4C: "Delete",
            0x4D: "End", 0x4E: "Page Down", 0x4F: "→", 0x50: "←", 0x51: "↓", 0x52: "↑", 0x53: "Num Lock", 0x54: "Keypad /",
            0x55: "Keypad *", 0x56: "Keypad -", 0x57: "Keypad +", 0x58: "Keypad Enter", 0x63: "Keypad .", 0x65: "Menu",
            0xE0: "Ctrl", 0xE1: "Shift", 0xE2: "Alt", 0xE3: "Cmd", 0xE4: "Right Ctrl", 0xE5: "Right Shift", 0xE6: "Right Alt", 0xE7: "Right Cmd",
            0xF0: "Mouse Left", 0xF1: "Mouse Right", 0xF2: "Mouse Middle",
        ]
        m.merge(named) { $1 }
        for i in 0..<12 { m[UInt8(0x3A + i)] = "F\(i + 1)" }
        for i in 0..<10 { m[UInt8(0x59 + i)] = "Keypad \(i + 1 > 9 ? 0 : i + 1)" }
        return m
    }()

    public static func name(_ usage: UInt8) -> String { names[usage] ?? String(format: "0x%02X", usage) }

    public static func modifierNames(_ mask: UInt8) -> String {
        var parts: [String] = []
        if mask & 0x01 != 0 { parts.append("Ctrl") }
        if mask & 0x02 != 0 { parts.append("Shift") }
        if mask & 0x04 != 0 { parts.append("Alt") }
        if mask & 0x08 != 0 { parts.append("Cmd") }
        return parts.joined(separator: "+")
    }

